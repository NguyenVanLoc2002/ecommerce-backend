CREATE TABLE return_exchanges (
    id CHAR(36) PRIMARY KEY,
    return_id CHAR(36) NOT NULL,
    order_item_id CHAR(36) NOT NULL,
    variant_id CHAR(36) NOT NULL,
    warehouse_id CHAR(36) NOT NULL,
    quantity INT NOT NULL,
    request_key VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    actor VARCHAR(255) NOT NULL,
    historical_price_evidence VARCHAR(500),
    status VARCHAR(40) NOT NULL,
    expires_at DATETIME(6),
    cancelled_by VARCHAR(255),
    cancelled_at DATETIME(6),
    created_at DATETIME NOT NULL,
    created_by VARCHAR(100),
    updated_at DATETIME NOT NULL,
    updated_by VARCHAR(100),
    CONSTRAINT fk_exchange_return FOREIGN KEY (return_id) REFERENCES order_returns(id),
    CONSTRAINT fk_exchange_order_item FOREIGN KEY (order_item_id) REFERENCES order_items(id),
    CONSTRAINT fk_exchange_variant FOREIGN KEY (variant_id) REFERENCES product_variants(id),
    CONSTRAINT fk_exchange_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
    CONSTRAINT uq_exchange_request_key UNIQUE (return_id, request_key),
    CONSTRAINT ck_exchange_quantity CHECK (quantity > 0)
);
